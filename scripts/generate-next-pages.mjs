// Generates the Next.js App Router tree (./app) from the expo-router screens
// in ./screens. Run via `npm run generate` (also runs before dev/build).
//
//   screens/_layout.tsx            -> app/layout.tsx (html shell + root layout)
//   screens/<dir>/_layout.tsx      -> app/<dir>/layout.tsx
//   screens/index.tsx              -> app/page.tsx                    (/)
//   screens/(tabs)/index.tsx       -> app/(tabs)/home/page.tsx        (/home)
//   screens/<dir>/index.tsx        -> app/<dir>/page.tsx
//   screens/<dir>/<name>.tsx       -> app/<dir>/<name>/page.tsx
//
// Route groups "(x)" and dynamic segments "[id]" mean the same thing in both
// routers, so the folder structure carries over. Every screen is rendered on
// the client only (ssr: false): the code was written for React Native and
// touches window/localStorage freely. ./app is fully generated — don't edit it.

import { mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, sep } from "node:path";

const ROOT = process.cwd();
const SCREENS = join(ROOT, "screens");
const APP = join(ROOT, "app");

const HEADER = "// AUTO-GENERATED by scripts/generate-next-pages.mjs — do not edit.\n";

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (/\.tsx$/.test(name) && !/\.(web|native|ios|android)\.tsx$/.test(name)) out.push(p);
  }
  return out;
}

const toPosix = (p) => p.split(sep).join("/");

function write(rel, content) {
  const file = join(APP, rel);
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, HEADER + content);
}

function pageFile(importPath) {
  return `"use client";

import dynamic from "next/dynamic";

const Screen = dynamic(() => import(${JSON.stringify(importPath)}), { ssr: false });

export default function Page() {
  return <Screen />;
}
`;
}

function layoutFile(importPath) {
  return `"use client";

import type { ReactNode } from "react";
import dynamic from "next/dynamic";
import { RouteContentProvider } from "expo-router";

const Layout = dynamic(() => import(${JSON.stringify(importPath)}), { ssr: false });

export default function GeneratedLayout({ children }: { children: ReactNode }) {
  return (
    <RouteContentProvider value={children}>
      <Layout />
    </RouteContentProvider>
  );
}
`;
}

const ROOT_LAYOUT = `import type { Metadata, Viewport } from "next";
import type { ReactNode } from "react";
import RootShell from "@/shims/next-root-shell";
import "../global.css";

export const metadata: Metadata = {
  title: "3names",
  description: "3names — campus social, study and games",
};

export const viewport: Viewport = {
  width: "device-width",
  initialScale: 1,
  viewportFit: "cover",
};

export default function RootLayout({ children }: { children: ReactNode }) {
  return (
    <html lang="en" suppressHydrationWarning>
      <body>
        <RootShell>{children}</RootShell>
      </body>
    </html>
  );
}
`;

const NOT_FOUND = `"use client";

import { Redirect } from "expo-router";

export default function NotFound() {
  return <Redirect href="/" />;
}
`;

rmSync(APP, { recursive: true, force: true });

const routes = new Map(); // url -> source, to catch collisions
let pages = 0;
let layouts = 0;

for (const file of walk(SCREENS).sort()) {
  const rel = toPosix(relative(SCREENS, file)).replace(/\.tsx$/, "");
  const importPath = "@/screens/" + rel;
  const parts = rel.split("/");
  const name = parts.pop();
  const dir = parts.join("/");

  if (name === "_layout") {
    if (dir === "") continue; // root layout is mounted by shims/next-root-shell
    write(`${dir}/layout.tsx`, layoutFile(importPath));
    layouts++;
    continue;
  }
  if (name.startsWith("_") || name.startsWith("+")) continue;
  // expo-router ignores files without a default export (shared helpers).
  if (!/export\s+default\b/.test(readFileSync(file, "utf8"))) {
    console.log(`  skipped (no default export): screens/${rel}.tsx`);
    continue;
  }

  let routeDir;
  if (name === "index") routeDir = dir === "(tabs)" ? "(tabs)/home" : dir;
  else routeDir = dir ? `${dir}/${name}` : name;

  const url = "/" + routeDir.split("/").filter((s) => s && !/^\(.*\)$/.test(s)).join("/");
  if (routes.has(url)) {
    throw new Error(`Route collision on ${url}: ${routes.get(url)} and ${rel}`);
  }
  routes.set(url, rel);

  write(routeDir ? `${routeDir}/page.tsx` : "page.tsx", pageFile(importPath));
  pages++;
}

write("layout.tsx", ROOT_LAYOUT);
write("not-found.tsx", NOT_FOUND);

console.log(`generate-next-pages: ${pages} pages, ${layouts + 1} layouts -> app/`);

// shims/lucide-react-native.ts: every lucide icon the app imports, wrapped so
// it accepts React Native styles (see shims/lucide-wrap.tsx). Anything not
// listed still resolves through `export *`, just without the style wrapper.
const ICON_RENAMES = { Balloon: "PartyPopper" }; // missing from this lucide-react release
const iconNames = new Set();
const CODE_DIRS = ["screens", "components", "hooks", "utils", "constants", "data"];
const walkCode = (dir, out = []) => {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walkCode(p, out);
    else if (/\.tsx?$/.test(name)) out.push(p);
  }
  return out;
};
for (const d of CODE_DIRS) {
  for (const file of walkCode(join(ROOT, d))) {
    const src = readFileSync(file, "utf8").replace(/\/\/.*$/gm, "");
    for (const m of src.matchAll(/import\s*\{([^}]*)\}\s*from\s*["']lucide-react-native["']/g)) {
      for (const part of m[1].split(",")) {
        const name = part.trim().replace(/^type\s+/, "").split(/\s+as\s+/)[0];
        if (/^[A-Z]\w*$/.test(name) && !/^(LucideIcon|LucideProps|Icon)$/.test(name)) iconNames.add(name);
      }
    }
  }
}
const iconLines = [...iconNames]
  .sort()
  .map((n) => `export const ${n} = wrapIcon(L.${ICON_RENAMES[n] ?? n});`);
writeFileSync(
  join(ROOT, "shims", "lucide-react-native.ts"),
  `// AUTO-GENERATED by scripts/generate-next-pages.mjs — do not edit.
// lucide-react-native -> lucide-react (same icon names and props).
import * as L from "lucide-react";
import { wrapIcon } from "./lucide-wrap";

export * from "lucide-react";
export type { NativeLucideProps as LucideProps } from "./lucide-wrap";

${iconLines.join("\n")}
`
);
console.log(`generate-next-pages: ${iconNames.size} lucide icons -> shims/lucide-react-native.ts`);
